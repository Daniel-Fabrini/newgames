// Prepares android/www (the web app that gets bundled inside the APK).
//
//   node tools/build-android-web.mjs [--maintenance id[,id...]]
//
// --maintenance replaces the listed games with an "under maintenance" screen and
// leaves their folders (scenes, build scripts…) out of the APK. Useful to ship an
// APK while one game is still being reworked.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'android', 'www');
const argIdx = process.argv.indexOf('--maintenance');
const maintenance = argIdx > -1 ? (process.argv[argIdx + 1] || '').split(',').filter(Boolean) : [];

const SKIP_DIRS = new Set(['node_modules', 'build', 'build3d', 'tools', 'test', 'tests', '__pycache__', '.git']);
const SKIP_EXT = new Set(['.md', '.txt', '.map', '.mjs', '.cjs', '.csv', '.py', '.pyc', '.blend']);
const SKIP_NAMES = new Set(['package.json', 'package-lock.json', '.gitignore']);

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

let count = 0;
let bytes = 0;
function copyDir(rel) {
  for (const entry of fs.readdirSync(path.join(root, rel), { withFileTypes: true })) {
    const r = path.join(rel, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      if (rel === 'games' && maintenance.includes(entry.name)) continue;
      copyDir(r);
      continue;
    }
    if (SKIP_EXT.has(path.extname(entry.name)) || SKIP_NAMES.has(entry.name)) continue;
    fs.mkdirSync(path.join(out, rel), { recursive: true });
    fs.copyFileSync(path.join(root, r), path.join(out, r));
    count++;
    bytes += fs.statSync(path.join(root, r)).size;
  }
}
for (const d of ['css', 'js', 'games', 'assets']) copyDir(d);
for (const f of ['index.html', 'manifest.webmanifest']) {
  fs.copyFileSync(path.join(root, f), path.join(out, f));
  count++;
}

// "Under maintenance" stub for the games being reworked.
for (const id of maintenance) {
  const dir = path.join(out, 'games', id);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(
    path.join(dir, 'main.js'),
    `// Maintenance stub generated by tools/build-android-web.mjs
const T = {
  pt: ['Em manutenção', 'Estamos melhorando este jogo. Volte em breve na próxima atualização!'],
  en: ['Under maintenance', 'We are improving this game. Come back soon in the next update!'],
  es: ['En mantenimiento', 'Estamos mejorando este juego. ¡Vuelve pronto en la próxima actualización!'],
};
export async function mount(root, ctx) {
  const { h } = ctx.ui;
  const [title, text] = T[ctx.lang] || T.en;
  root.append(h('div', { class: 'screen center' }, h('div', { class: 'big-emoji' }, '🛠️'), h('h2', { class: 'page-title' }, title), h('p', { class: 'muted', style: { maxWidth: '30ch' } }, text)));
  return () => {};
}
`,
  );
  count++;
}

console.log(`android/www: ${count} files, ${(bytes / 1024 / 1024).toFixed(1)} MB${maintenance.length ? ` · maintenance: ${maintenance.join(', ')}` : ''}`);
