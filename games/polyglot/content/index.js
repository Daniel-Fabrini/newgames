const cache = new Map();

// Loads the content of a ready unit (cached). Resolves to the unit object (see CONTENT.md).
export function loadUnit(id) {
  const entry = UNITS.find((u) => u.id === id);
  if (!entry || !entry.ready) return Promise.reject(new Error('unit not available: ' + id));
  if (!cache.has(id)) {
    cache.set(
      id,
      import(`./units/${entry.file}`).then((m) => ({ ...entry, ...m.default, id: entry.id })),
    );
  }
  return cache.get(id);
}

export const readyUnits = () => UNITS.filter((u) => u.ready);
