// Build-time: merges tests/found/*.json (planner output) into ../solutions.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, 'found');
const out = {};
for (const f of fs.readdirSync(dir).sort()) if (f.endsWith('.json')) out[f.replace('.json', '')] = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
let s = '// Generated by tests/merge.mjs from the planner output: reference solutions (verified by tests/goo.test.mjs).\nexport default {\n';
for (const [id, v] of Object.entries(out)) {
  s += `  ${id}: { sol: [${v.sol.map((p) => `{ type: '${p.type}', x: ${p.x}, y: ${p.y} }`).join(', ')}], stock: ${JSON.stringify(v.stock).replace(/"/g, '')}, stars: ${JSON.stringify(v.stars)} },\n`;
}
s += '};\n';
fs.writeFileSync(path.join(here, '..', 'solutions.js'), s);
console.log('merged', Object.keys(out).length);
