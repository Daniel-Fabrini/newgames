"""Pack rendered frames into WebP atlases + games/squad/atlas.js (run with system python3 + PIL).

    python3 -I games/squad/build/pack.py <SQUAD_TMP>

Each frame is trimmed to its alpha bounding box; the anchor (feet / ground point)
and any extra anchors are stored relative to the trimmed frame:
    name: [x, y, w, h, ax, ay, ppm, {extra anchors}]
"""
import glob
import json
import os
import sys

from PIL import Image, ImageEnhance

HERE = os.path.dirname(os.path.abspath(__file__))
GAME = os.path.dirname(HERE)
ASSETS = os.path.join(GAME, 'assets')
TMP = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('SQUAD_TMP', '/tmp/squad_build')
FR = os.path.join(TMP, 'frames')
TEX = os.environ.get('PH_TEXTURES', '/tmp/claude-0/-home-user-newgames/337c13fa-8c03-56c4-b57a-40498e6cdc26/scratchpad/hog3d/cache/textures')

GROUPS = {
    'units': ['blue_*', 'red_*', 'shd_*', 'bru_*', 'dead_*', 'dbru_*'],
    'heroes': ['hgunner_*', 'hheavy_*', 'hrocket_*'],
    'props': ['ped_*', 'crate', 'w[0-9]', 'ring', 'stone*'],
    'rocks': ['rock*'],
}
# optional downscale per group (keeps the download small)
SCALE = {'units': 1.0, 'heroes': 1.0, 'props': 1.0, 'rocks': 1.0}
MAXW = 2048


def load(name):
    im = Image.open(os.path.join(FR, name + '.png')).convert('RGBA')
    meta = json.load(open(os.path.join(FR, name + '.json')))
    return im, meta


def pack(group, pats):
    names = []
    for p in pats:
        names += sorted(os.path.basename(f)[:-4] for f in glob.glob(os.path.join(FR, p + '.png')))
    items = []
    k = SCALE[group]
    for n in names:
        im, meta = load(n)
        if k != 1:
            im = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
        bb = im.getchannel('A').point(lambda a: 255 if a > 6 else 0).getbbox() or (0, 0, 1, 1)
        x0, y0 = max(0, bb[0] - 1), max(0, bb[1] - 1)
        x1, y1 = min(im.width, bb[2] + 1), min(im.height, bb[3] + 1)
        crop = im.crop((x0, y0, x1, y1))
        ex = {kk: [round(v[0] * k - x0, 1), round(v[1] * k - y0, 1)] for kk, v in meta.items() if kk not in ('ppm', 'a')}
        items.append(dict(n=n, im=crop, ax=round(meta['a'][0] * k - x0, 1), ay=round(meta['a'][1] * k - y0, 1), ppm=meta['ppm'] * k, ex=ex))
    # shelf pack, tallest first
    order = sorted(items, key=lambda it: -it['im'].height)
    x = y = sh = 0
    W = 0
    for it in order:
        w, h = it['im'].size
        if x + w + 2 > MAXW:
            x, y, sh = 0, y + sh + 2, 0
        it['x'], it['y'] = x, y
        x += w + 2
        sh = max(sh, h)
        W = max(W, x)
    H = y + sh
    atlas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    for it in items:
        atlas.paste(it['im'], (it['x'], it['y']))
    out = os.path.join(ASSETS, group + '.webp')
    atlas.save(out, 'WEBP', quality=86, method=6, alpha_quality=90)
    frames = {}
    for it in items:
        row = [it['x'], it['y'], it['im'].width, it['im'].height, it['ax'], it['ay'], round(it['ppm'], 2)]
        if it['ex']:
            row.append(it['ex'])
        frames[it['n']] = row
    print(group, f'{W}x{H}', len(items), 'frames', os.path.getsize(out) // 1024, 'KB')
    return frames


def road():
    """Seamless light concrete/sand road tile from a CC0 Poly Haven texture (tileable)."""
    from PIL import ImageOps, ImageFilter
    src = os.path.join(TEX, 'concrete_floor_worn_001', 'diff.jpg')
    g = ImageOps.autocontrast(Image.open(src).convert('L').resize((512, 512), Image.LANCZOS), cutoff=1).filter(ImageFilter.GaussianBlur(1.6))
    base = (204, 192, 174)
    amt = 0.3

    def ch(c):
        return g.point(lambda v: max(0, min(255, int(c + (v - 128) * amt))))
    im = Image.merge('RGB', tuple(ch(c) for c in base))
    out = os.path.join(ASSETS, 'road.webp')
    im.save(out, 'WEBP', quality=78, method=6)
    print('road', os.path.getsize(out) // 1024, 'KB')


os.makedirs(ASSETS, exist_ok=True)
data = {g: pack(g, p) for g, p in GROUPS.items()}
road()
js = '// Generated by build/pack.py — sprite atlases rendered in Blender (build/*.py).\n'
js += '// frame: [x, y, w, h, anchorX, anchorY, pixelsPerMetre, {extra anchors}]\n'
js += 'export const ATLAS = ' + json.dumps(data, separators=(',', ':')) + ';\n'
open(os.path.join(GAME, 'atlas.js'), 'w').write(js)
print('atlas.js written')
